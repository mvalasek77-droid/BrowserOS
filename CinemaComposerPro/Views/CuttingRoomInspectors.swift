    @ObservedObject var doc: CutDocument
    var placed: PlacedItem
    @State private var markerName: String = ""

    private var item: TimelineItem { placed.item }

    var body: some View {
        List {
            Section(item.name) {
                KeyValueRow(key: "Lane", value: placed.lane == 0 ? "Primary storyline" : "Lane \(placed.lane)")
                KeyValueRow(key: "Start", value: placed.start.timecode(at: doc.rate))
                KeyValueRow(key: "End", value: placed.end.timecode(at: doc.rate))
                KeyValueRow(key: "Duration", value: item.duration.timecode(at: doc.rate))
                KeyValueRow(key: "Source in", value: item.sourceIn.timecode(at: doc.rate))
                KeyValueRow(key: "Role", value: item.role.label)
