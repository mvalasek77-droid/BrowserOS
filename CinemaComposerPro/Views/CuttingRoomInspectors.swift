                } label: {
                    Label(item.isEnabled ? "Disable clip" : "Enable clip",
                          systemImage: item.isEnabled ? "eye.slash" : "eye")
                }
                Button {
                    doc.toggleLockOnSelection()
                } label: {
                    Label(item.isLocked ? "Unlock clip" : "Lock clip",
                          systemImage: item.isLocked ? "lock.open" : "lock")
                }
                HStack {
                    Button {
