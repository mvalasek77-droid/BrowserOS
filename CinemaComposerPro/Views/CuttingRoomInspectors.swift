import SwiftUI

/// A slider that only writes an undo step when the finger lifts. Dragging one
/// would otherwise bury the undo stack under a hundred intermediate values.
struct CommitSlider: View {
    var label: String
    var range: ClosedRange<Double>
    var step: Double
    var format: (Double) -> String
    var initial: Double
    var commit: (Double) -> Void

    @State private var value: Double = 0
    @State private var isEditing = false

    var body: some View {
        VStack(alignment: .leading, spacing: 2) {
            HStack {
                Text(label).font(.caption)
                Spacer()
                Text(format(value)).font(.caption.monospacedDigit()).foregroundStyle(.secondary)
            }
            Slider(value: $value, in: range, step: step) { editing in
                isEditing = editing
                if !editing { commit(value) }
            }
        }
        .onAppear { value = initial }
        .onChange(of: initial) { _, new in
            if !isEditing { value = new }
        }
    }
}

